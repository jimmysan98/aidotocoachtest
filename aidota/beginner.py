def role_training_plan(position: int) -> str:
    """Простой план тренировки на роль: 3 шага-упражнения."""
    pos = normalize_position(position) or 1
    steps = role_training_steps(pos)
    numbered = " ".join(f"{index}) {step}" for index, step in enumerate(steps, 1))
    return f"План тренировки на роль {position_label(pos)}: {numbered}"


def next_drill(position: int, seed_text: str = "") -> str:
    """Одно упражнение под роль. Детерминировано для одинакового ``seed_text``."""
    pos = normalize_position(position) or 1
    drills = _ROLE_DRILLS[pos]
    seed = str(seed_text or "")
    digest = hashlib.md5(seed.encode("utf-8")).hexdigest()
    index = int(digest[:8], 16) % len(drills)
    return drills[index]
