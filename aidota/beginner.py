_RU_ENDINGS: tuple[str, ...] = tuple(
    sorted(
        (
            "ами", "ями", "ого", "его", "ому", "ему", "ыми", "ими", "ией",
            "иям", "иях", "ию", "ия", "ии", "ей", "ой", "ый", "ий", "ая",
            "яя", "ое", "ее", "ые", "ие", "ов", "ев", "ам", "ям", "ах",
            "ях", "ом", "ем", "ую", "юю", "а", "я", "ы", "и", "у", "ю",
            "е", "о", "ь",
        ),
        key=len,
        reverse=True,
    )
)

_TERM_PATTERN_CACHE: list[tuple[str, re.Pattern[str], bool]] | None = None


def _stem(word: str) -> str:
    """Отрезает типичное русское окончание, оставляя основу слова.

    Основа должна быть не короче 4 символов: иначе короткие корни вроде
    «маг» начинают ложно совпадать с посторонними словами («магазине»).
    """
    for ending in _RU_ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= 4:
            return word[: -len(ending)]
    return word


def _word_pattern(word: str) -> str:
    if re.fullmatch(r"[0-9a-z]+", word):
        return re.escape(word)
    if len(word) <= 3:
        return re.escape(word)
    stem = _stem(word)
    if stem == word:
        return re.escape(word) + r"[а-я]*"
    return re.escape(stem) + r"[а-я]*"


def _form_pattern(form: str) -> re.Pattern[str] | None:
    words = [word for word in form.split() if word]
    if not words:
        return None
    body = r"\s+".join(_word_pattern(word) for word in words)
    return re.compile(rf"(?<![0-9a-zа-я]){body}(?![0-9a-zа-я])")


def _term_index() -> list[tuple[str, re.Pattern[str], bool]]:
    """Скомпилированные шаблоны терминов: (канон, шаблон, это_канон)."""
    global _TERM_PATTERN_CACHE
    if _TERM_PATTERN_CACHE is not None:
        return _TERM_PATTERN_CACHE
    index: list[tuple[str, re.Pattern[str], bool]] = []
    for canonical, entry in GLOSSARY.items():
        canonical_pattern = _form_pattern(_normalize_text(canonical))
        if canonical_pattern is not None:
            index.append((canonical, canonical_pattern, True))
        for alias in entry.get("aliases", ()):  # type: ignore[union-attr]
            pattern = _form_pattern(_normalize_text(alias))
            if pattern is not None:
                index.append((canonical, pattern, False))
    _TERM_PATTERN_CACHE = index
    return index


def resolve_term(text: Any) -> tuple[str, dict[str, Any]] | None:
    """Находит термин Dota 2 в свободной фразе.

    Устойчив к падежам («байбека», «вижна», «руны мудрости») и алиасам
    («БКБ», «bkb», «пулл», «аегис»). Возвращает ``(каноническое_имя, запись)``
    или ``None``, если термина нет.
    """
    prepared = _normalize_text(text)
    if not prepared:
        return None
    best: tuple[int, int, int, str] | None = None  # (длина, канон, -начало, ключ)
    best_key: str | None = None
    for canonical, pattern, is_canonical in _term_index():
        match = pattern.search(prepared)
        if match is None:
            continue
        span = match.end() - match.start()
        score = (span, 1 if is_canonical else 0, -match.start())
        if best is None or score > best[:3]:
            best = (score[0], score[1], score[2], canonical)
            best_key = canonical
    if best_key is None:
        return None
    return best_key, GLOSSARY[best_key]


def _capitalize_first(text: str) -> str:
    for index, char in enumerate(text):
        if char.isalpha():
            return text[:index] + char.upper() + text[index + 1:]
    return text


def explain_term(text: Any) -> str | None:
    """Возвращает простое объяснение термина или ``None``, если термин не найден.

    Формат: 1–2 простых предложения плюс короткий пример. Без markdown.
    """
    resolved = resolve_term(text)
    if resolved is None:
        return None
    _term, entry = resolved
    simple = " ".join(str(entry.get("simple") or "").split())
    example = " ".join(str(entry.get("example") or "").split())
    if not simple:
        return None
    result = simple if not example else f"{simple} {example}"
    result = " ".join(_capitalize_first(result).split())
    if result and result[-1] not in ".!?…":
        result += "."
    return result


