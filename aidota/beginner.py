def _normalize_text(text: Any) -> str:
    """Нижний регистр, ё → е, только буквы/цифры/пробелы."""
    raw = str(text or "").lower().replace("ё", "е")
    return " ".join(re.sub(r"[^0-9a-zа-я]+", " ", raw).split())


def normalize_skill_level(value: Any) -> str:
    """Приводит уровень игрока к одному из :data:`SKILL_LEVELS`.

    Понимает русские и английские алиасы («новичок», «нуб», «любитель»,
    «средний», «опытный», «продвинутый», «профи», «эксперт», «про»).
    Невалидное значение нормализуется в ``"beginner"``.
    """
    if isinstance(value, str):
        text = _normalize_text(value)
        if text:
            if text in SKILL_LEVELS:
                return text
            # Дефисные формы («про-игрок») уже схлопнуты в «про игрок».
            for level, aliases in _LEVEL_ALIASES:
                for alias in aliases:
                    if text == alias:
                        return level
            for level, aliases in _LEVEL_ALIASES:
                for alias in aliases:
                    if len(alias) < 4:
                        continue
                    pattern = rf"(?<![0-9a-zа-я]){re.escape(alias)}(?![0-9a-zа-я])"
                    if re.search(pattern, text):
                        return level
            # Короткие алиасы («про», «топ») принимаем только как точное
            # значение целиком — иначе «супер-мега-про» ложно станет expert.
    return "beginner"


def level_label(level: Any) -> str:
    """Человеческое название уровня: «Новичок», «Любитель», «Опытный», «Профи»."""
    return _LEVEL_LABELS[normalize_skill_level(level)]


def is_experienced(level: Any) -> bool:
    """True для advanced/expert — стиль ответов без разжёвывания базовых терминов."""
    return normalize_skill_level(level) in ("advanced", "expert")


